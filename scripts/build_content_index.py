#!/usr/bin/env python3
"""Write content.json: a snapshot of every file under media/ and notes/ (plus resume.pdf).

The home page reads the live GitHub tree API on *.github.io and falls back to this
file anywhere else, or when the API is unavailable. It also takes each file's date
from here, because the tree API has no dates.

Each entry: {"path", "size" (bytes), "date" (ISO 8601 last commit date; the file's
modification time if it is not committed yet)}, plus "w" and "h" (pixels) for images
when Pillow is installed, so the gallery can lay out before the photos load.

Run from anywhere (stdlib only; Pillow optional, for image sizes):
    python3 scripts/build_content_index.py
Commit content.json whenever media/ or notes/ change.
"""

import datetime
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FOLDERS = ("media", "notes")
EXTRA = ("resume.pdf",)
SKIP = {".gitkeep", ".DS_Store", "Thumbs.db", "desktop.ini"}
IMAGE_EXTS = (".jpg", ".jpeg", ".png", ".webp", ".avif")

try:
    from PIL import Image, ImageOps
except ImportError:
    Image = None


def commit_date(rel):
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cI", "--", rel],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        out = ""
    if out:
        return out
    mtime = os.path.getmtime(os.path.join(ROOT, rel))
    return datetime.datetime.fromtimestamp(mtime, datetime.timezone.utc).isoformat(timespec="seconds")


def image_size(rel):
    """(width, height) as displayed, after the EXIF rotation; None without Pillow."""
    if Image is None or not rel.lower().endswith(IMAGE_EXTS):
        return None
    try:
        with Image.open(os.path.join(ROOT, rel)) as im:
            return ImageOps.exif_transpose(im).size
    except OSError:
        return None


def entry(rel):
    e = {
        "path": rel,
        "size": os.path.getsize(os.path.join(ROOT, rel)),
        "date": commit_date(rel),
    }
    size = image_size(rel)
    if size:
        e["w"], e["h"] = size
    return e


def main():
    files = []
    for folder in FOLDERS:
        base = os.path.join(ROOT, folder)
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
            for name in sorted(filenames):
                if name in SKIP or name.startswith("."):
                    continue
                rel = os.path.relpath(os.path.join(dirpath, name), ROOT).replace(os.sep, "/")
                files.append(entry(rel))
    for rel in EXTRA:
        if os.path.isfile(os.path.join(ROOT, rel)):
            files.append(entry(rel))
    files.sort(key=lambda f: f["path"])

    out = {"note": "Generated by scripts/build_content_index.py. Do not edit by hand.", "files": files}
    with open(os.path.join(ROOT, "content.json"), "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print("content.json: %d files" % len(files), file=sys.stderr)


if __name__ == "__main__":
    main()
